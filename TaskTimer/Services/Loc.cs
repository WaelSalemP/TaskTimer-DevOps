namespace TaskTimer.Services;

/// <summary>Minimal English/Arabic string table; switching language also flips forms to right-to-left.</summary>
public static class Loc
{
    public static bool IsArabic { get; set; }

    public static string T(string key) =>
        Strings.TryGetValue(key, out var s) ? (IsArabic ? s.Ar : s.En) : key;

    public static string T(string key, params object[] args) => string.Format(T(key), args);

    public static void ApplyDirection(Form form)
    {
        form.RightToLeft = IsArabic ? RightToLeft.Yes : RightToLeft.No;
        form.RightToLeftLayout = IsArabic;
    }

    private static readonly string[] HijriMonthsEn =
    {
        "Muharram", "Safar", "Rabi' I", "Rabi' II", "Jumada I", "Jumada II", "Rajab", "Sha'ban", "Ramadan", "Shawwal",
        "Dhu al-Qi'dah", "Dhu al-Hijjah"
    };

    private static readonly string[] HijriMonthsAr =
    {
        "محرم", "صفر", "ربيع الأول", "ربيع الآخر", "جمادى الأولى", "جمادى الآخرة", "رجب", "شعبان", "رمضان", "شوال",
        "ذو القعدة", "ذو الحجة"
    };

    private static readonly System.Globalization.UmAlQuraCalendar Hijri = new();
    private static readonly System.Globalization.CultureInfo EnglishDates = new("en-US");
    private static readonly System.Globalization.CultureInfo ArabicDates = new("ar-EG"); // Arabic names, Gregorian calendar

    /// <summary>Hijri date by the Umm al-Qura calendar, e.g. "14 Rabi' II 1448".</summary>
    public static string HijriDate(DateTime date)
    {
        var months = IsArabic ? HijriMonthsAr : HijriMonthsEn;
        return $"{Hijri.GetDayOfMonth(date)} {months[Hijri.GetMonth(date) - 1]} {Hijri.GetYear(date)}";
    }

    public static string GregorianDate(DateTime date) =>
        date.ToString("dddd, d MMMM yyyy", IsArabic ? ArabicDates : EnglishDates);

    public static string ClockTime(DateTime date) => date.ToString("hh:mm:ss tt", IsArabic ? ArabicDates : EnglishDates);

    public static MessageBoxOptions MsgOptions =>
        IsArabic ? MessageBoxOptions.RtlReading | MessageBoxOptions.RightAlign : 0;

